from jsonschema import Draft202012Validator
from publication_process import SealedBytes

from genealogy.publication_inputs import read_input, strict_json

_UUID = "[0-9a-f]{8}-[0-9a-f]{4}-7[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}"
_PERSON = {"type": "string", "pattern": "^per_" + _UUID + r"\Z"}
_SOURCE = {"type": "string", "pattern": "^src_" + _UUID + r"\Z"}
# No route, selector, regex, template or program fields. Encode query text as a value.
_TEXT = {"type": "string", "pattern": r"^[\w][\w '.’–-]{0,119}\Z"}


def series(item: dict[str, Any], length: int) -> dict[str, Any]:
    return {
        "type": "array",
        "items": item,
        "minItems": length,
        "maxItems": length,
        "uniqueItems": True,
    }


def count(minimum: int, maximum: int) -> dict[str, Any]:
    return {"type": "integer", "minimum": minimum, "maximum": maximum}


FIELDS: dict[str, dict[str, Any]] = {
    "current": {
        **dict.fromkeys(("aliasPerson", "previewPerson", "treePerson", "otherPerson"), _PERSON),
        **dict.fromkeys(
            (
                "preferredName",
                "birthName",
                "compactDate",
                "previewQuery",
                "estateContext",
                "citationText",
                "treeQuery",
                "otherQuery",
                "sourceQuery",
            ),
            _TEXT,
        ),
        "relationshipPeople": series(_PERSON, 12),
        "searchTerms": series(_TEXT, 9),
        "aliases": series(_TEXT, 3),
        "sparseTerms": series(_TEXT, 3),
        "sparsePeople": series(_PERSON, 3),
        "previewSource": _SOURCE,
        "previewLinks": count(4, 100),
        "reportTotal": count(31, 50),
        "searchTotal": count(1, 25),
        "imageMatches": count(1, 25),
        "reportMatches": count(1, 25),
    },
    "historical": {
        **dict.fromkeys(("senior", "child", "infant"), _PERSON),
        "query": _TEXT,
        "heading": _TEXT,
        "matches": count(1, 25),
    },
    "auth": {
        "senior": _PERSON,
        "living": _PERSON,
        "asset": {"type": "string", "pattern": "^ast_" + _UUID + r"\Z"},
        "query": _TEXT,
        "livingName": _TEXT,
    },
    "indicators": {"reviewedPeople": series(_PERSON, 11)},
}


@dataclass(frozen=True)
class ScenarioInputs:
    path: Path
    raw: bytes

    @classmethod
    def load(cls, path: Path, kind: str) -> ScenarioInputs:
        raw = read_input(path)
        value = strict_json(raw)
        fields = {"schema_version": {"const": 1}, "kind": {"const": kind}, **FIELDS[kind]}
        schema = {
            "type": "object",
            "properties": fields,
            "required": list(fields),
            "additionalProperties": False,
        }
        if (
            not Draft202012Validator(schema).is_valid(value)
            or type(value["schema_version"]) is not int
        ):
            raise ValueError("invalid browser expectation schema")
        if kind == "current" and not set(value["sparseTerms"]) <= set(value["searchTerms"]):
            raise ValueError("sparse browser routes must be exercised")
        return cls(path, raw)

    def verify(self) -> None:
        if read_input(self.path) != self.raw:
            raise ValueError("browser expectations changed during execution")


def run_browser(
    script: Path, raw: bytes, env: dict[str, str], scenario: ScenarioInputs | None = None
) -> None:
    """Only the sealed, validated or controller-generated bytes reach the child."""
    with closing(SealedBytes(raw, label="browser")) as sealed:
        if scenario is not None:
            scenario.verify()
        try:
            subprocess.run(
                ["node", str(script)],
                cwd=script.parent.parent,
                env={
                    **os.environ,
                    **env,
                    "BROWSER_INPUT_FD": str(sealed.fd),
                    "BROWSER_INPUT_SHA256": sealed.hash.hex(),
                },
                pass_fds=(sealed.fd,),
                check=True,
            )
        finally:
            sealed.verify()
            if scenario is not None:
                scenario.verify()
